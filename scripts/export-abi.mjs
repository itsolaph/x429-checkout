// Writes the X429Checkout ABI and creation bytecode from the Foundry build into packages/x429/src/
// (abi.ts as a const for viem types; bytecode.ts for `npx x429 deploy`, so users need no forge).
// Usage: forge build --root contracts && node scripts/export-abi.mjs [--check]
//   --check  exits 1 if the committed files differ from the build (nothing is written)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = JSON.parse(readFileSync(join(root, "contracts/out/X429Checkout.sol/X429Checkout.json"), "utf8"));
const header = "// Generated by scripts/export-abi.mjs from contracts/src/X429Checkout.sol. Do not edit.";
const compiler = artifact.metadata?.compiler?.version ?? "unknown";
const settings = artifact.metadata?.settings ?? {};
const files = {
  "packages/x429/src/abi.ts": `${header}\nexport const checkoutAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  "packages/x429/src/bytecode.ts":
    `${header}\n` +
    `// solc ${compiler}, optimizer ${settings.optimizer?.enabled ? `on (${settings.optimizer.runs} runs)` : "off"}, evm ${settings.evmVersion ?? "default"}.\n` +
    `/** Creation bytecode of X429Checkout; constructor(address usdc, address operator). */\n` +
    `export const checkoutBytecode = "${artifact.bytecode.object}" as const;\n` +
    `export const checkoutCompiler = ${JSON.stringify({ solc: compiler, optimizerRuns: settings.optimizer?.enabled ? settings.optimizer.runs : 0, evmVersion: settings.evmVersion ?? null })} as const;\n`,
};

const check = process.argv.includes("--check");
let stale = 0;
for (const [rel, text] of Object.entries(files)) {
  const path = join(root, rel);
  if (check) {
    let cur = "";
    try {
      cur = readFileSync(path, "utf8");
    } catch {}
    if (cur !== text) {
      console.error(`stale: ${rel}`);
      stale++;
    }
  } else {
    writeFileSync(path, text);
    console.log(`wrote ${rel}`);
  }
}
if (check) {
  if (stale) process.exit(1);
  console.log(`up to date (${artifact.abi.length} ABI entries, ${(artifact.bytecode.object.length - 2) / 2} bytes of creation code)`);
}
