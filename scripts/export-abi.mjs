// Writes the X429Checkout ABI from the Foundry build into server/src/abi.ts (as a const for viem types).
// Usage: forge build --root contracts && node scripts/export-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = JSON.parse(readFileSync(join(root, "contracts/out/X429Checkout.sol/X429Checkout.json"), "utf8"));
const out = `// Generated by scripts/export-abi.mjs from contracts/src/X429Checkout.sol. Do not edit.
export const checkoutAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
writeFileSync(join(root, "server/src/abi.ts"), out);
console.log(`wrote server/src/abi.ts (${artifact.abi.length} ABI entries)`);
